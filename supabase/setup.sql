drop policy if exists "products update" on public.products;
create policy "products update" on public.products for update using (owns_shop(shop_id) or is_admin());
drop policy if exists "products delete" on public.products;
create policy "products delete" on public.products for delete using (owns_shop(shop_id) or is_admin());

drop policy if exists "orders read" on public.orders;
create policy "orders read" on public.orders for select using (
  customer_id = auth.uid() or owns_shop(shop_id) or delivery_id = auth.uid() or is_admin()
  or (my_role() = 'delivery' and status = 'packed' and delivery_id is null));

drop policy if exists "otp read" on public.order_otps;
create policy "otp read" on public.order_otps for select using (
  exists (select 1 from orders o where o.id = order_id and o.customer_id = auth.uid()));

drop policy if exists "reviews read" on public.reviews;
create policy "reviews read" on public.reviews for select using (true);

drop policy if exists "wishlist own" on public.wishlist;
create policy "wishlist own" on public.wishlist for all using (customer_id = auth.uid()) with check (customer_id = auth.uid());

