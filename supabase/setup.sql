create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- tables
create table if not exists public.profiles (
  id uuid primary key references auth.users on delete cascade,
  role text not null default 'customer' check (role in ('customer','owner','delivery','admin')),
  name text not null default '',
  phone text not null,
  address text default '',
  area text default '',
  lat double precision,
  lng double precision,
  vehicle text default '',
  online boolean default false,
  status text not null default 'active' check (status in ('active','pending','blocked')),
  created_at timestamptz default now()
);

create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  delivery_fee numeric default 20,
  free_delivery_above numeric default 499,
  commission numeric default 5,
  delivery_pay numeric default 25,
  radius_km numeric default 10,
  auto_approve_products boolean default false,
  support_phone text default ''
);
insert into public.settings (id) values (1) on conflict do nothing;

create table if not exists public.shops (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references public.profiles on delete set null,
  name text not null,
  category text not null,
  description text default '',
  address text default '',
  area text default '',
  lat double precision,
  lng double precision,
  phone text default '',
  photo_url text default '',
  icon text default '🏪',
  open boolean default true,
  open_time text default '07:00',
  close_time text default '22:00',
  eta int default 20,
  upi_id text default '',
  status text not null default 'pending' check (status in ('pending','approved','blocked')),
  rating_avg numeric default 0,
  rating_count int default 0,
  created_at timestamptz default now()
);

-- private payout / KYC details: only shop owner + admin can read
create table if not exists public.shop_private (
  shop_id uuid primary key references public.shops on delete cascade,
  account_holder text default '',
  bank_name text default '',
  account_number text default '',
  ifsc text default '',
  pan text default '',
  gst text default '',
  license_no text default '',
  owner_aadhaar_last4 text default ''
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops on delete cascade,
  name text not null,
  subcategory text default 'Other',
  description text default '',
  price numeric not null check (price >= 0),
  mrp numeric,
  unit text default '',
  photo_url text default '',
  emoji text default '📦',
  in_stock boolean default true,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity (start with 1001) primary key,
  customer_id uuid references public.profiles on delete set null,
  customer_name text, customer_phone text,
  shop_id uuid references public.shops on delete set null,
  delivery_id uuid references public.profiles on delete set null,
  delivery_name text, delivery_phone text,
  items jsonb not null,
  item_total numeric not null,
  delivery_fee numeric not null default 0,
  total numeric not null,
  payment text default 'COD',
  address text, lat double precision, lng double precision,
  note text default '',
  status text not null default 'placed',
  history jsonb not null default '[]',
  rated boolean default false,
  created_at timestamptz default now()
);

create table if not exists public.order_otps (
  order_id bigint primary key references public.orders on delete cascade,
  otp text not null
);

create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  order_id bigint unique references public.orders on delete cascade,
  shop_id uuid references public.shops on delete cascade,
  customer_id uuid references public.profiles on delete set null,
  customer_name text,
  rating int not null check (rating between 1 and 5),
  comment text default '',
  created_at timestamptz default now()
);

create table if not exists public.wishlist (
  customer_id uuid not null default auth.uid() references public.profiles on delete cascade,
  product_id uuid not null references public.products on delete cascade,
  created_at timestamptz default now(),
  primary key (customer_id, product_id)
);

create index if not exists products_shop_idx on public.products(shop_id);
create index if not exists orders_shop_idx on public.orders(shop_id);
create index if not exists orders_customer_idx on public.orders(customer_id);
create index if not exists orders_delivery_idx on public.orders(delivery_id);

-- ---------------------------------------------------------------- helpers
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = 'admin' and status = 'active');
$$;

create or replace function public.my_role() returns text
language sql stable security definer set search_path = public as $$
  select role from profiles where id = auth.uid() and status = 'active';
$$;

create or replace function public.owns_shop(p_shop uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from shops where id = p_shop and owner_id = auth.uid());
$$;

create or replace function public.admin_exists() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where role = 'admin');
$$;

-- new auth user -> profile row
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare r text := coalesce(new.raw_user_meta_data->>'role', 'customer');
begin
  if r not in ('customer','owner','delivery') then r := 'customer'; end if;
  insert into profiles (id, role, name, phone, address, area, lat, lng, vehicle, status)
  values (
    new.id, r,
    coalesce(new.raw_user_meta_data->>'name', ''),
    coalesce(new.raw_user_meta_data->>'phone', ''),
    coalesce(new.raw_user_meta_data->>'address', ''),
    coalesce(new.raw_user_meta_data->>'area', ''),
    nullif(new.raw_user_meta_data->>'lat', '')::double precision,
    nullif(new.raw_user_meta_data->>'lng', '')::double precision,
    coalesce(new.raw_user_meta_data->>'vehicle', ''),
    case when r = 'delivery' then 'pending' else 'active' end
  );
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- first person to call this becomes admin (only works while no admin exists)
create or replace function public.claim_admin() returns void
language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from profiles where role = 'admin') then
    raise exception 'Admin already exists';
  end if;
  perform set_config('mb.bypass', 'on', true);
  update profiles set role = 'admin', status = 'active' where id = auth.uid();
end $$;

-- non-admins cannot change their own role / status / phone
create or replace function public.guard_profile() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if coalesce(current_setting('mb.bypass', true), '') = 'on' or is_admin() then return new; end if;
  new.role := old.role; new.status := old.status; new.phone := old.phone;
  return new;
end $$;
drop trigger if exists guard_profile on public.profiles;
create trigger guard_profile before update on public.profiles
  for each row execute function public.guard_profile();

-- non-admins: new shops are pending; cannot approve / change owner / ratings
create or replace function public.guard_shop() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if coalesce(current_setting('mb.bypass', true), '') = 'on' or is_admin() then return new; end if;
  if tg_op = 'INSERT' then
    new.status := 'pending'; new.owner_id := auth.uid(); new.rating_avg := 0; new.rating_count := 0;
  else
    new.status := old.status; new.owner_id := old.owner_id;
    new.rating_avg := old.rating_avg; new.rating_count := old.rating_count;
  end if;
  return new;
end $$;
drop trigger if exists guard_shop on public.shops;
create trigger guard_shop before insert or update on public.shops
  for each row execute function public.guard_shop();

-- non-admins: new products pending (unless auto approve); cannot approve
create or replace function public.guard_product() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if coalesce(current_setting('mb.bypass', true), '') = 'on' or is_admin() then return new; end if;
  if tg_op = 'INSERT' then
    new.status := case when (select auto_approve_products from settings where id = 1) then 'approved' else 'pending' end;
  else
    new.status := old.status;
  end if;
  return new;
end $$;
drop trigger if exists guard_product on public.products;
create trigger guard_product before insert or update on public.products
  for each row execute function public.guard_product();

-- ---------------------------------------------------------------- order RPCs
create or replace function public.place_order(
  p_shop uuid, p_items jsonb, p_address text, p_lat double precision, p_lng double precision,
  p_payment text, p_note text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  me profiles; s shops; st settings; it jsonb; p products;
  items jsonb := '[]'; sub numeric := 0; fee numeric; oid bigint; q int;
begin
  select * into me from profiles where id = auth.uid();
  if me is null or me.role <> 'customer' or me.status <> 'active' then raise exception 'Only customers can order'; end if;
  select * into s from shops where id = p_shop;
  if s is null or s.status <> 'approved' then raise exception 'Shop not available'; end if;
  if not s.open then raise exception 'Shop is closed now'; end if;
  select * into st from settings where id = 1;

  for it in select * from jsonb_array_elements(p_items) loop
    q := greatest(1, least(50, (it->>'qty')::int));
    select * into p from products where id = (it->>'id')::uuid and shop_id = p_shop;
    if p is null or p.status <> 'approved' then raise exception 'A product is not available'; end if;
    if not p.in_stock then raise exception '% is out of stock', p.name; end if;
    items := items || jsonb_build_object('id', p.id, 'name', p.name, 'price', p.price, 'qty', q,
      'unit', p.unit, 'photo_url', p.photo_url, 'emoji', p.emoji);
    sub := sub + p.price * q;
  end loop;
  if jsonb_array_length(items) = 0 then raise exception 'Cart is empty'; end if;

  fee := case when sub >= st.free_delivery_above then 0 else st.delivery_fee end;
  insert into orders (customer_id, customer_name, customer_phone, shop_id, items, item_total, delivery_fee, total,
    payment, address, lat, lng, note, status, history)
  values (me.id, me.name, me.phone, p_shop, items, sub, fee, sub + fee,
    case when p_payment in ('COD','UPI') then p_payment else 'COD' end,
    p_address, p_lat, p_lng, coalesce(p_note, ''), 'placed',
    jsonb_build_array(jsonb_build_object('status', 'placed', 'at', now())))
  returning id into oid;
  insert into order_otps values (oid, lpad((floor(random() * 10000))::int::text, 4, '0'));
  return oid;
end $$;

create or replace function public.update_order_status(p_id bigint, p_status text, p_otp text default null)
returns void
language plpgsql security definer set search_path = public as $$
declare o orders; me profiles; ok boolean := false; real_otp text;
begin
  select * into o from orders where id = p_id for update;
  if o is null then raise exception 'Order not found'; end if;
  select * into me from profiles where id = auth.uid();
  if me is null or me.status <> 'active' then raise exception 'Not allowed'; end if;
  select otp into real_otp from order_otps where order_id = p_id;

  if me.role = 'admin' then
    ok := true;
  elsif me.role = 'customer' and o.customer_id = me.id then
    ok := (o.status = 'placed' and p_status = 'cancelled');
  elsif me.role = 'owner' and owns_shop(o.shop_id) then
    ok := (o.status = 'placed' and p_status in ('accepted','rejected'))
       or (o.status = 'accepted' and p_status = 'packed')
       or (o.status = 'packed' and p_status = 'out_for_delivery' and o.delivery_id is null)
       or (o.status = 'out_for_delivery' and p_status = 'delivered' and o.delivery_id is null);
    if ok and p_status = 'out_for_delivery' then
      update orders set delivery_name = 'Shop delivery', delivery_phone = (select phone from shops where id = o.shop_id) where id = p_id;
    end if;
  elsif me.role = 'delivery' then
    if o.status = 'packed' and o.delivery_id is null and p_status = 'out_for_delivery' then
      ok := true;
      update orders set delivery_id = me.id, delivery_name = me.name, delivery_phone = me.phone where id = p_id;
    elsif o.delivery_id = me.id and o.status = 'out_for_delivery' and p_status = 'delivered' then
      ok := true;
    end if;
  end if;

  if not ok then raise exception 'This status change is not allowed'; end if;
  if p_status = 'delivered' and me.role <> 'admin' and coalesce(p_otp, '') <> real_otp then
    raise exception 'Wrong OTP. Ask the customer for the 4-digit delivery OTP.';
  end if;

  update orders set status = p_status,
    history = history || jsonb_build_array(jsonb_build_object('status', p_status, 'at', now()))
  where id = p_id;
end $$;

create or replace function public.rate_order(p_id bigint, p_rating int, p_comment text)
returns void
language plpgsql security definer set search_path = public as $$
declare o orders;
begin
  select * into o from orders where id = p_id;
  if o is null or o.customer_id <> auth.uid() or o.status <> 'delivered' or o.rated then
    raise exception 'Cannot rate this order';
  end if;
  insert into reviews (order_id, shop_id, customer_id, customer_name, rating, comment)
  values (p_id, o.shop_id, o.customer_id, o.customer_name, greatest(1, least(5, p_rating)), coalesce(p_comment, ''));
  update orders set rated = true where id = p_id;
  perform set_config('mb.bypass', 'on', true);
  update shops set
    rating_count = (select count(*) from reviews where shop_id = o.shop_id),
    rating_avg = (select round(avg(rating)::numeric, 1) from reviews where shop_id = o.shop_id)
  where id = o.shop_id;
end $$;

